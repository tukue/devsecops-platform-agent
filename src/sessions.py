import logging
import threading
import uuid
from collections import OrderedDict

logger = logging.getLogger(__name__)

MAX_BOUND_SESSIONS = 1000


class SessionRegistry:
    """Server-minted conversation sessions bound to a caller identity.

    Session IDs are generated by the server and mapped to an owner key (the
    Gradio browser session hash), so a blank or foreign client-supplied ID can
    never address another user's history. Requested IDs are only honored for
    unowned server-side callers that already track their own sessions.
    """

    def __init__(self, max_bound_sessions=MAX_BOUND_SESSIONS):
        self.max_bound_sessions = max_bound_sessions
        self._lock = threading.Lock()
        self._bound = OrderedDict()

    @staticmethod
    def new_session_id():
        return f"session_{uuid.uuid4().hex[:16]}"

    def resolve(self, requested=None, owner=None, create=True):
        """Return the ``(session_id, created)`` pair for this request.

        - With an owner, the bound session wins and any requested ID is
          ignored, so an owner can only ever reach their own history.
        - Without an owner, a non-empty requested ID is trusted (server-side
          callers manage their own sessions) and anything else gets a new
          server-generated ID. Empty or whitespace IDs are never reused as a
          shared key.
        - Unowned sessions are deliberately not retained in the registry:
          without an owner identity there is nothing safe to key them on, so
          an unowned caller must thread the returned ID into its next call or
          every call gets its own empty history. ``analyze_ingested_findings``
          resolves once per batch and passes that ID down for this reason.
        - With ``create=False`` nothing is minted or bound; an unbound caller
          gets ``None``.
        """
        if isinstance(requested, str):
            requested = requested.strip() or None

        with self._lock:
            if owner:
                bound = self._bound.get(owner)
                if bound:
                    if requested and requested != bound:
                        logger.debug("Ignoring session id that is not owned by this caller.")
                    return bound, False
                if not create:
                    return None, False
                session_id = self.new_session_id()
                self._bind(owner, session_id)
                return session_id, True

            if requested:
                return requested, False
            if not create:
                return None, False
            return self.new_session_id(), True

    def _bind(self, owner, session_id):
        self._bound[owner] = session_id
        self._bound.move_to_end(owner)
        while len(self._bound) > self.max_bound_sessions:
            self._bound.popitem(last=False)
